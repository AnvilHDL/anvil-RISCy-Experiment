#!/usr/bin/env python3
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path


def run(cmd, cwd=None):
    subprocess.run(cmd, cwd=cwd, check=True)


def choose_tools():
    gcc = shutil.which("riscv64-unknown-elf-gcc")
    objcopy = shutil.which("riscv64-unknown-elf-objcopy")
    if gcc and objcopy:
        return ("gcc", gcc, objcopy)

    clang = shutil.which("clang")
    llvm_objcopy = shutil.which("llvm-objcopy")
    if clang and llvm_objcopy:
        return ("clang", clang, llvm_objcopy)

    raise SystemExit("[fpga-bram-init] need riscv64-unknown-elf-gcc+objcopy or clang+llvm-objcopy")


def choose_march(cc_kind, cc):
    candidates = ["rv64im_zicsr", "rv64im"]
    test_src = ".section .text._start\n.globl _start\n_start:\n  ret\n"

    with tempfile.TemporaryDirectory(prefix="fpga-bram-isa-") as td:
        td = Path(td)
        src = td / "probe.S"
        obj = td / "probe.o"
        src.write_text(test_src, encoding="ascii")

        for march in candidates:
            if cc_kind == "gcc":
                cmd = [
                    cc,
                    f"-march={march}",
                    "-mabi=lp64",
                    "-nostdlib",
                    "-ffreestanding",
                    "-c",
                    str(src),
                    "-o",
                    str(obj),
                ]
            else:
                cmd = [
                    cc,
                    "--target=riscv64-unknown-elf",
                    f"-march={march}",
                    "-mabi=lp64",
                    "-nostdlib",
                    "-ffreestanding",
                    "-c",
                    str(src),
                    "-o",
                    str(obj),
                ]
            if subprocess.run(cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL).returncode == 0:
                return march

    raise SystemExit("[fpga-bram-init] could not find a supported rv64im toolchain ISA")


def main():
    if len(sys.argv) != 4:
        raise SystemExit("usage: gen_fpga_bram_init.py <src.S> <link.ld> <out.vh>")

    src = Path(sys.argv[1]).resolve()
    link = Path(sys.argv[2]).resolve()
    out = Path(sys.argv[3]).resolve()
    root = src.parents[1]

    kind, cc, objcopy = choose_tools()
    march = choose_march(kind, cc)
    out.parent.mkdir(parents=True, exist_ok=True)

    with tempfile.TemporaryDirectory(prefix="fpga-bram-init-") as td:
        td = Path(td)
        elf = td / "bringup.elf"
        binfile = td / "bringup.bin"

        common = [
            f"-march={march}",
            "-mabi=lp64",
            "-mcmodel=medany",
            "-nostdlib",
            "-ffreestanding",
            "-T", str(link),
        ]

        if kind == "gcc":
            cmd = [cc, *common, str(src), "-o", str(elf)]
        else:
            cmd = [
                cc,
                "--target=riscv64-unknown-elf",
                "-fuse-ld=lld",
                *common,
                str(src),
                "-o",
                str(elf),
            ]

        run(cmd, cwd=root)
        run([objcopy, "-O", "binary", str(elf), str(binfile)], cwd=root)
        blob = binfile.read_bytes()

    if not blob:
        raise SystemExit("[fpga-bram-init] produced empty binary")

    words = []
    for idx in range(0, len(blob), 8):
        chunk = blob[idx:idx + 8]
        if len(chunk) < 8:
            chunk = chunk + bytes(8 - len(chunk))
        words.append(int.from_bytes(chunk, "little"))

    with out.open("w", encoding="ascii") as fh:
        fh.write("// Generated by scripts/gen_fpga_bram_init.py from fpga/programs/bringup_bram.S\n")
        fh.write("// Keep this file in the FPGA RTL output directory next to risky_genesys2_bram_top.sv.\n")
        for idx, word in enumerate(words):
            fh.write(f"        bram[{idx}] = 64'h{word:016x};\n")
            fh.write(f"        bram_mem[{idx}] = 64'h{word:016x};\n")


if __name__ == "__main__":
    main()
